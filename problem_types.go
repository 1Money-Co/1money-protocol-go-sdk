// IsKnownType reports whether Type is in this SDK's copy of the node's problem
// catalog. The match is exact; "about:blank" is not known. On a transaction
// submission, decide on Action only when IsKnownType is true.
func (p Problem) IsKnownType() bool {
	id, ok := strings.CutPrefix(p.Type, ProblemTypePrefix)
	if !ok {
		return false
	}
	_, known := knownProblemTypes[id]
	return known
}
